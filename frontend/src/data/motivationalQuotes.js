export function quoteForTask(taskId) {
  const s = String(taskId);
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = (h * 31 + s.charCodeAt(i)) >>> 0;
  }
  return MOTIVATIONAL_QUOTES[h % MOTIVATIONAL_QUOTES.length];
}
